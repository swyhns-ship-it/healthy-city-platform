def match(pathway):
    """返回与该路径相关的证据卡片(关键词命中因果链 + 落题一致)。最多 2 张,按 link 去重。"""
    text = " ".join(pathway.get("chain", [])).lower()
    q = pathway.get("outcome_q")
    seen, out = set(), []
    for c in CARDS:
        if q in c["q"] and any(k.lower() in text for k in c["keys"]):
            if c["link"] in seen:
                continue
            seen.add(c["link"])
            out.append({"link": c["link"], "strength": c["strength"], "sources": c["sources"]})
        if len(out) >= 2:
            break
    return out


def annotate(pathways):
    """给每条路径加 cards 字段(可能为空 → 显示端标'机制推断·待专家补证')。"""
    for p in pathways:
        p["cards"] = match(p)
    return pathways


